                Directory.CreateDirectory(Path.Combine(root, folder));
            }

            var config = new JsonObject
            {
                ["schemaVersion"] = 2,
                ["groups"] = new JsonArray([.. groups.Select(g => (JsonNode)(g.Color is null ? new JsonObject { ["id"] = g.Id, ["folder"] = g.Folder } : new JsonObject { ["id"] = g.Id, ["folder"] = g.Folder, ["color"] = g.Color }))]),
