    /// <summary>A board without what writing it to files may change: tab names, and the order of tags.</summary>
    private static JsonNode Comparable(JsonNode board)
    {
        var copy = JsonNode.Parse(BoardSerializer.Serialize(BoardSerializer.Deserialize(board.ToJsonString())))!;
        foreach (var group in copy["groups"]!.AsArray())
        {
            group!["name"] = "-";
        }

        void Visit(JsonNode? item)
        {
            if (item?["tags"] is JsonArray tags)
            {
                item["tags"] = new JsonArray([.. tags.Select(t => t!.GetValue<string>()).Order(StringComparer.Ordinal).Select(t => (JsonNode)t)]);
            }

            foreach (var child in item?["children"]?.AsArray() ?? [])
            {
                Visit(child);
            }
        }

        foreach (var item in copy["items"]!.AsArray())
        {
            Visit(item);
        }

        return copy;
    }

    private static async Task<JsonNode?> ReadVaultAsync(JsonObject files, JsonArray folders)
    {
        var temp = Path.Combine(Path.GetTempPath(), "tt-fixture-" + Guid.NewGuid().ToString("N"));
        var root = Path.Combine(temp, "vault");
        try
        {
            foreach (var folder in folders)
            {
                Directory.CreateDirectory(Path.Combine(root, folder!.GetValue<string>()));
            }

            foreach (var (path, text) in files)
            {
                var full = Path.Combine(root, path.Replace('/', Path.DirectorySeparatorChar));
                Directory.CreateDirectory(Path.GetDirectoryName(full)!);
                await File.WriteAllTextAsync(full, text!.GetValue<string>());
            }

            using var store = VaultBoardStore.Open(new VaultOptions(root) { TimeZone = Zone, Time = new FakeTimeProvider(Now), LockDirectory = Path.Combine(temp, "locks"), Watch = false, EditSettleTime = TimeSpan.Zero });
            return JsonNode.Parse(await store.ReadAsync(BoardSerializer.Serialize));
        }
        finally
        {
            Directory.Delete(temp, recursive: true);
        }
    }

    internal static TaskMarkdownContext Context(string path)
    {
        var slash = path.LastIndexOf('/');
        return new TaskMarkdownContext(Zone, Now, slash < 0 ? string.Empty : path[..slash], path);
    }

    private static async Task<JsonObject> RenderCaseAsync(string name, TaskBoard built)
    {
        var boardJson = FixtureFile.FixIds(BoardSerializer.Serialize(built));
        var temp = Path.Combine(Path.GetTempPath(), "tt-fixture-" + Guid.NewGuid().ToString("N"));
        var root = Path.Combine(temp, "vault");
        var locks = Path.Combine(temp, "locks");
        try
        {
            Directory.CreateDirectory(locks);
            var legacy = Path.Combine(locks, "board.json");
            await File.WriteAllTextAsync(legacy, boardJson);
            var files = new JsonObject();
            var sync = new JsonArray();
            JsonNode? parsed;
            using (var store = VaultBoardStore.Open(new VaultOptions(root) { TimeZone = Zone, Time = new FakeTimeProvider(Now), LockDirectory = locks, LegacyBoardPath = legacy, Watch = false, EditSettleTime = TimeSpan.Zero }))
            {
                parsed = JsonNode.Parse(await store.ReadAsync(BoardSerializer.Serialize));
                var snapshot = await store.ReadSyncAsync();
                foreach (var entry in snapshot.Entries.Values.OrderBy(e => e.Key, StringComparer.Ordinal))
                {
                    var item = new JsonObject { ["key"] = entry.Key, ["path"] = entry.Path, ["hash"] = entry.Hash };
                    if (!File.Exists(Path.Combine(root, entry.Path)))
                    {
                        item["content"] = Encoding.UTF8.GetString(snapshot.Read(entry));
                    }

                    sync.Add(item);
                }
            }

            foreach (var file in Directory.EnumerateFiles(root, "*", SearchOption.AllDirectories)
                .Select(f => Path.GetRelativePath(root, f).Replace('\\', '/'))
                .Where(f => f != "AGENTS.md" && !f.StartsWith(".todo-tracker/trash/", StringComparison.Ordinal))
                .Order(StringComparer.Ordinal))
            {
                files[file] = await File.ReadAllTextAsync(Path.Combine(root, file));
            }

            var folders = new JsonArray([.. Directory.EnumerateDirectories(root).Select(Path.GetFileName).Where(d => d is not null && d[0] is not ('.' or '_')).Order(StringComparer.Ordinal).Select(d => (JsonNode)d!)]);
            return new JsonObject { ["name"] = name, ["board"] = JsonNode.Parse(boardJson), ["folders"] = folders, ["files"] = files, ["sync"] = sync, ["parsed"] = parsed };
        }
        finally
        {
            Directory.Delete(temp, recursive: true);
        }
    }

