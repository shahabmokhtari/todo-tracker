                if (change is not null)
                {
                    await store.UpdateAsync(b =>
                    {
                        var group = b.Groups.Single(g => g.Name == change["group"]!.GetValue<string>());
                        if (change["kind"]!.GetValue<string>() == "rename")
                        {
                            b.UpdateGroup(group.Id, change["to"]!.GetValue<string>(), group.Color, Actor.User, Now);
                        }
                        else
                        {
                            b.DeleteGroup(group.Id, b.Groups.Single(g => g.Name == change["moveTo"]!.GetValue<string>()).Id, Actor.User, Now);
                        }

