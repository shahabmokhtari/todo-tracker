    [Fact]
    public async Task Every_render_case_reads_back_as_the_board_it_came_from()
    {
        foreach (var c in FixtureFile.Read("vault/render.json")["cases"]!.AsArray())
        {
            // The files, put in an empty folder and read, are the board in "parsed" (that is what the ports read them as).
            var reread = await ReadVaultAsync(c!["files"]!.AsObject(), c["folders"]!.AsArray());
            Assert.True(JsonNode.DeepEquals(c["parsed"], reread), $"{c["name"]}: the files don't read back as \"parsed\".");

            // Written and read back, a board keeps everything but tab names (they're folder names) and the order of
            // a subtask's tags (one-word tags first: they're on the line, the others in its hidden data).
            var written = Comparable(c["board"]!);
            var read = Comparable(c["parsed"]!);
            Assert.True(JsonNode.DeepEquals(written, read), $"{c["name"]}: the board read back lost something.");

            // Every file parses, and writing a parsed file again (nothing changed) gives exactly the same text.
            foreach (var (path, text) in c["files"]!.AsObject())
            {
                if (path.EndsWith(".md", StringComparison.Ordinal))
                {
                    var context = Context(path);
                    var file = TaskMarkdown.Parse(text!.GetValue<string>(), Path.GetFileNameWithoutExtension(path), context);
                    Assert.False(file.NeedsWrite, $"{path} would be rewritten");
                    Assert.Equal(text.GetValue<string>(), TaskMarkdown.Render(file.Root, context, file));
                }
            }

            // The sync entries are the files' hashes.
            foreach (var entry in c["sync"]!.AsArray())
            {
                var path = entry!["path"]!.GetValue<string>();
                var content = entry["content"]?.GetValue<string>() ?? c["files"]![path]!.GetValue<string>();
                Assert.Equal(entry["hash"]!.GetValue<string>(), SyncHash.Of(Encoding.UTF8.GetBytes(content)));
            }
        }
    }

