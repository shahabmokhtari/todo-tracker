    [Fact]
    public void Planning_on_either_device_ends_with_the_same_files()
    {
        // Each pair of cases "x (on a)" / "x (on b)" is the same sync worked out on both devices: once each applied
        // its plan, both hold the same files at the same paths.
        var fixture = FixtureFile.Read("sync/planner.json")["cases"]!.AsArray();
        var pairs = fixture.Where(c => c!["name"]!.GetValue<string>().EndsWith(" (on a)", StringComparison.Ordinal)).ToList();
        Assert.NotEmpty(pairs);
        foreach (var onA in pairs)
        {
            var name = onA!["name"]!.GetValue<string>()[..^" (on a)".Length];
            var onB = fixture.Single(c => c!["name"]!.GetValue<string>() == name + " (on b)")!;
            Assert.Equal(Apply(onA), Apply(onB));
        }

        static string Apply(JsonNode c)
        {
            var files = c["local"]!["entries"]!.AsArray().ToDictionary(e => e!["path"]!.GetValue<string>(), e => e!["text"]!.GetValue<string>(), StringComparer.Ordinal);
            foreach (var op in c["expected"]!["ops"]!.AsArray())
            {
                var path = op!["path"]!.GetValue<string>();
                switch (op["kind"]!.GetValue<string>())
                {
                    case "move":
                        files[op["to"]!.GetValue<string>()] = files[path];
                        files.Remove(path);
                        break;
                    case "delete":
                        files.Remove(path);
                        break;
                    case "write" or "setConfig" or "setOrder":
                        files[path] = op["text"]!.GetValue<string>();
                        break;
                    case "appendActivity":
                        files[path] = files.GetValueOrDefault(path, string.Empty) + op["text"]!.GetValue<string>();
                        break;
                }
            }

            return string.Join("\n---\n", files.OrderBy(f => f.Key, StringComparer.Ordinal).Select(f => $"{f.Key}\n{f.Value}"));
        }
    }

