    private static JsonObject RunPlan(PlanCase c)
    {
        var blobs = new Dictionary<string, byte[]>(StringComparer.Ordinal);
        SyncEntry E((string Key, string Path, string Text) e)
        {
            var bytes = Encoding.UTF8.GetBytes(e.Text);
            var entry = new SyncEntry(e.Key, e.Path, SyncHash.Of(bytes));
            blobs[entry.Hash] = bytes;
            return entry;
        }

        SyncSide Side(SideSpec s) => new(s.Device, s.Name, s.Entries.Select(E).ToDictionary(e => e.Key, StringComparer.Ordinal), e => blobs[e.Hash]);
        var local = Side(c.Local);
        var peer = Side(c.Peer);
        var old = c.Base.Select(E).ToDictionary(e => e.Key, StringComparer.Ordinal);
        var deleted = (c.Deleted ?? []).Select(d => (d.Key, SyncHash.Of(Encoding.UTF8.GetBytes(d.Text)))).ToHashSet();
        var options = new SyncPlanOptions
        {
            Deleted = e => deleted.Contains((e.Key, e.Hash)),
            IsValidTask = c.ValidateTasks ? IsValidTask : (_, _) => true,
        };
        var plan = SyncPlanner.Plan(local, peer, old, h => blobs.GetValueOrDefault(h), options);

        JsonObject Side2(SideSpec s) => new() { ["device"] = s.Device, ["name"] = s.Name, ["entries"] = Entries(s.Entries) };
        return new JsonObject
        {
            ["name"] = c.Name,
            ["local"] = Side2(c.Local),
            ["peer"] = Side2(c.Peer),
            ["base"] = Entries(c.Base),
            ["deleted"] = new JsonArray([.. (c.Deleted ?? []).Select(d => (JsonNode)new JsonObject { ["key"] = d.Key, ["hash"] = SyncHash.Of(Encoding.UTF8.GetBytes(d.Text)) })]),
            ["validateTasks"] = c.ValidateTasks,
            ["expected"] = new JsonObject
            {
                ["ops"] = new JsonArray([.. plan.Ops.Select(o => (JsonNode)new JsonObject
                {
                    ["kind"] = KindName(o.Kind),
                    ["path"] = o.Path,
                    ["expected"] = o.Expected,
                    ["to"] = o.To,
                    ["text"] = o.Content is null ? null : Encoding.UTF8.GetString(o.Content),
                })]),
                ["conflicts"] = new JsonArray([.. plan.Conflicts.Select(x => (JsonNode)new JsonObject
                {
                    ["key"] = x.Key,
                    ["path"] = x.Path,
                    ["peer"] = x.Peer,
                    ["peerName"] = x.PeerName,
                    ["mine"] = x.Mine,
                    ["theirs"] = x.Theirs,
                    ["base"] = x.Base,
                    ["result"] = x.Result,
                })]),
            },
        };
    }

    private static string KindName(SyncOpKind kind) => kind switch
    {
        SyncOpKind.Write => "write",
        SyncOpKind.Move => "move",
        SyncOpKind.Delete => "delete",
        SyncOpKind.AppendActivity => "appendActivity",
        SyncOpKind.SetConfig => "setConfig",
        _ => "setOrder",
    };

    private static bool IsValidTask(string path, string text)
    {
        try
        {
            TaskMarkdown.Parse(text, Path.GetFileNameWithoutExtension(path), VaultFixtureTests.Context(path));
            return true;
        }
        catch (VaultFormatException)
        {
            return false;
        }
    }

    private static JsonArray Entries(IEnumerable<(string Key, string Path, string Text)> entries) =>
        new([.. entries.Select(e => (JsonNode)new JsonObject { ["key"] = e.Key, ["path"] = e.Path, ["text"] = e.Text, ["hash"] = SyncHash.Of(Encoding.UTF8.GetBytes(e.Text)) })]);

    private static JsonArray Entries(IEnumerable<SyncEntry> entries) =>
        new([.. entries.Select(e => (JsonNode)new JsonObject { ["key"] = e.Key, ["path"] = e.Path, ["hash"] = e.Hash })]);

    private static Dictionary<string, SyncEntry> Index((string Key, string Path, string Text)[] entries) =>
        entries.Select(e => new SyncEntry(e.Key, e.Path, SyncHash.Of(Encoding.UTF8.GetBytes(e.Text)))).ToDictionary(e => e.Key, StringComparer.Ordinal);

    private static List<string> SplitLines(string text)
    {
        var lines = new List<string>();
        var start = 0;
        for (var i = 0; i < text.Length; i++)
        {
            if (text[i] == '\n')
            {
                lines.Add(text[start..(i + 1)]);
                start = i + 1;
            }
        }

        if (start < text.Length)
        {
            lines.Add(text[start..]);
        }

        return lines;
    }
