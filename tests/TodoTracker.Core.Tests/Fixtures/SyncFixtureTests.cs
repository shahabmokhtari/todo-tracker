    private static IEnumerable<(string Name, string Base, string First, string Second, bool Keyed, ConflictPolicy Policy)> MergeCases()
    {
        static string L(params string[] lines) => string.Concat(lines.Select(l => l + "\n"));
        yield return ("different lines combine", L("a", "b", "c", "d"), L("a", "B", "c", "d"), L("a", "b", "c", "D"), false, ConflictPolicy.Both);
        yield return ("the same change once", L("a", "b", "c"), L("a", "X", "c"), L("a", "X", "c"), false, ConflictPolicy.Both);
        yield return ("insertions at start and end", L("x", "y"), L("first", "x", "y"), L("x", "y", "last"), false, ConflictPolicy.Both);
        yield return ("one side deletes, the other keeps", L("a", "b", "c"), L("a", "c"), L("a", "b", "c"), false, ConflictPolicy.Both);
        yield return ("delete against edit keeps the edit", L("a", "b", "c"), L("a", "c"), L("a", "B", "c"), false, ConflictPolicy.Both);
        yield return ("same line changed: both kept", L("a", "b", "c"), L("a", "mine", "c"), L("a", "theirs", "c"), false, ConflictPolicy.Both);
        yield return ("same line changed: first", L("a", "b", "c"), L("a", "mine", "c"), L("a", "theirs", "c"), false, ConflictPolicy.First);
        yield return ("same line changed: second", L("a", "b", "c"), L("a", "mine", "c"), L("a", "theirs", "c"), false, ConflictPolicy.Second);
        yield return ("both add at the same place", L("a", "z"), L("a", "one", "two", "z"), L("a", "two", "three", "z"), false, ConflictPolicy.Both);
        yield return ("empty base", string.Empty, L("mine"), L("theirs"), false, ConflictPolicy.Both);
        yield return ("last line without a newline", "a\nb", "a\nb\nc", "z\na\nb", false, ConflictPolicy.Both);
        yield return ("a newline added at the end", "a\nb", "a\nb\n", "a\nB", false, ConflictPolicy.Both);
        yield return ("crlf lines", "a\r\nb\r\nc\r\n", "a\r\nB\r\nc\r\n", "a\r\nb\r\nC\r\n", false, ConflictPolicy.Both);
        yield return ("unicode lines", L("Café", "naïve", "日本"), L("Café ☕", "naïve", "日本"), L("Café", "naïve", "日本語"), false, ConflictPolicy.Both);
        yield return ("one step checked, the next renamed", Trip, TaskText("Plan the trip", "", "Lisbon in spring.\n", FlightsDone, Hotel, Pack), TaskText("Plan the trip", "", "Lisbon in spring.\n", Flights, HotelRenamed, Pack), true, ConflictPolicy.Both);
