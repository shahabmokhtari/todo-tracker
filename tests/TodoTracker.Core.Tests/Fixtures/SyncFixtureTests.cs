    private static readonly Dictionary<string, byte[]> Manifested = [];

    private static SyncEntry Entry(string key, string path, string text, DateTimeOffset since)
    {
        var bytes = Encoding.UTF8.GetBytes(text);
        var hash = SyncHash.Of(bytes);
        lock (Manifested)
        {
            Manifested[hash] = bytes;
        }

        return new SyncEntry(key, path, hash) { Since = since };
    }

    private static byte[] ContentOf(SyncEntry e)
    {
        lock (Manifested)
        {
            return Manifested[e.Hash];
        }
    }

