using System.Text.Json.Nodes;

namespace OneThing.Core.Tests.Fixtures;

/// <summary>
/// tests/fixtures/focus-lengths.json: how long the focus timer's sessions and breaks may be (each bound, and one past
/// it), what each change leaves, and the line it adds to the timeline. A refused change changes nothing. Swift
/// (FocusLengthFixtureTests) and Kotlin (FocusLengthFixtureTest) read the same file. Regenerate: set
/// ONETHING_WRITE_FIXTURES=1 and run this test.
/// </summary>
public sealed class FocusLengthFixtureTests
{
    private static readonly DateTimeOffset T0 = new(2026, 1, 5, 9, 0, 0, TimeSpan.Zero);

    private static readonly (string Name, int Max)[] Fields =
    [
        ("focusMinutes", TaskBoard.MaxFocusMinutes),
        ("shortBreakMinutes", TaskBoard.MaxShortBreakMinutes),
        ("longBreakMinutes", TaskBoard.MaxLongBreakMinutes),
        ("focusesBeforeLongBreak", TaskBoard.MaxFocusesBeforeLongBreak),
    ];

    [Fact]
    public void The_focus_length_fixture_is_what_the_core_allows()
    {
        var board = new TaskBoard();
        var steps = new JsonArray();
        int[] current = [25, 5, 15, 4];
        foreach (var (index, (_, max)) in Fields.Index())
        {
            foreach (var value in new[] { 0, 1, max, max + 1 })
            {
                var asked = (int[])current.Clone();
                asked[index] = value;
                var step = new JsonObject { ["set"] = Settings(asked) };
                var before = board.Activity.Count;
                try
                {
                    board.SetFocusLengths(asked[0], asked[1], asked[2], asked[3], Actor.Agent("claude"), T0);
                    step["ok"] = true;
                    step["summary"] = board.Activity[^1].Summary;
                    Assert.Equal(before + 1, board.Activity.Count);
                    Assert.Equal(Actor.Agent("claude"), board.Activity[^1].Actor);
                }
                catch (ArgumentOutOfRangeException)
                {
                    step["ok"] = false;
                    Assert.Equal(before, board.Activity.Count);
                }

                var s = board.Pomodoro.Settings;
                current = [s.FocusMinutes, s.ShortBreakMinutes, s.LongBreakMinutes, s.FocusesBeforeLongBreak];
                step["settings"] = Settings(current);
                steps.Add(step);
            }
        }

        FixtureFile.Check("focus-lengths.json", new JsonObject
        {
            ["about"] = "The focus timer's lengths, in minutes, and how many sessions before a long break: each bound and one past it. A step with \"ok\": false is refused and changes nothing (no timeline line); one that's allowed leaves \"settings\" and adds \"summary\" to the timeline, by whoever changed it. Generated by the C# core (FocusLengthFixtureTests), checked by Swift (FocusLengthFixtureTests) and Kotlin (FocusLengthFixtureTest).",
            ["start"] = Settings([25, 5, 15, 4]),
            ["limits"] = new JsonObject(Fields.Select(f => KeyValuePair.Create(f.Name, (JsonNode?)new JsonArray(1, f.Max)))),
            ["steps"] = steps,
        });
    }

    private static JsonObject Settings(int[] v) => new(Fields.Select((f, i) => KeyValuePair.Create(f.Name, (JsonNode?)v[i])));
}
