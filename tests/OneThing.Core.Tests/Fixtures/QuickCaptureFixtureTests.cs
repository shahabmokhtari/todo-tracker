using System.Globalization;
using System.Text.Json;
using System.Text.Json.Nodes;
using OneThing.Core;

namespace OneThing.Core.Tests.Fixtures;

/// <summary>
/// tests/fixtures/quick-capture.json: what one typed line becomes (title, tags, priority, snooze, deadline), so the
/// phone and Mac apps that read it on their own add the same task the server would.
/// </summary>
public sealed class QuickCaptureFixtureTests
{
    // Monday 2026-01-05, 06:30 in Los Angeles.
    private static readonly DateTimeOffset Now = new(2026, 1, 5, 14, 30, 0, TimeSpan.Zero);
    private const string ZoneId = "America/Los_Angeles";

    private static readonly string[] Inputs =
    [
        "  Deploy feature X ",
        "Plan trip #personal #travel/japan #Personal !",
        "Write the plan #\"deep work\" #q3 #\"Deep  Work\"",
        "Write the plan #\u201Cdeep work\u201D",
        "Fix bug #123",
        "Fix bug #",
        "Fix bug ##heading",
        "Fix bug #a,b",
        "Fix bug !",
        "Fix bug !!",
        "Fix bug !!!",
        "Fix bug !low",
        "Fix bug !HIGH",
        "!urgent Fix bug",
        "Fix bug !normal",
        "Check metrics @15m",
        "Check metrics @2h",
        "Check metrics @1d",
        "Call Bob @tomorrow",
        "Call Bob @fri",
        "Ship it due:today",
        "Ship it due:tomorrow",
        "Ship it due:3d",
        "Ship it due:2026-02-01",
        "Email @someone about it",
        "Wow! great",
        "due:someday cleanup",
        "Ship due:2026-13-01",
        "Ship @+5m",
        "Report #work !! @2h due:tomorrow",
    ];

    private static readonly string[] Rejected = ["", "   ", "!! @2h", "#work !"];

    [Fact]
    public void The_quick_capture_fixture_is_what_this_version_reads_from_each_line()
    {
        var zone = TimeZoneInfo.FindSystemTimeZoneById(ZoneId);
        var cases = new JsonArray();
        foreach (var text in Inputs)
        {
            var capture = QuickCaptureParser.Parse(text, Now, zone);
            cases.Add(new JsonObject
            {
                ["text"] = text,
                ["title"] = capture.Title,
                ["tags"] = new JsonArray([.. capture.Tags.Select(t => (JsonNode)t)]),
                ["priority"] = JsonNamingPolicy.CamelCase.ConvertName(capture.Priority.ToString()),
                ["snoozeUntil"] = Instant(capture.NextActionAt, zone),
                ["deadline"] = Instant(capture.Deadline, zone),
            });
        }

        foreach (var text in Rejected)
        {
            Assert.Throws<ArgumentException>(() => QuickCaptureParser.Parse(text, Now, zone));
        }

        FixtureFile.Check("quick-capture.json", new JsonObject
        {
            ["about"] = "Quick capture: what one typed line becomes. Each case is read at \"now\" in \"timeZone\": its title, "
                + "tags (in order, without repeats), priority (low, normal, high, critical), snoozeUntil (when it comes "
                + "back, or null) and deadline (or null), as instants with the zone's offset. \"rejected\" lines have no "
                + "title and add nothing. Generated by the C# core (QuickCaptureFixtureTests); Swift and Kotlin read it.",
            ["now"] = Now.UtcDateTime.ToString("yyyy-MM-dd'T'HH:mm:ss'Z'", CultureInfo.InvariantCulture),
            ["timeZone"] = ZoneId,
            ["cases"] = cases,
            ["rejected"] = new JsonArray([.. Rejected.Select(t => (JsonNode)t)]),
        });
    }

    private static string? Instant(DateTimeOffset? value, TimeZoneInfo zone) =>
        value is { } v ? TimeZoneInfo.ConvertTime(v, zone).ToString("yyyy-MM-dd'T'HH:mm:sszzz", CultureInfo.InvariantCulture) : null;
}
