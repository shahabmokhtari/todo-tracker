    fun allows(c: Char): Boolean {
        val code = c.code
        var lo = 0
        var hi = ranges.size / 2 - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            when {
                code < ranges[mid * 2] -> hi = mid - 1
                code > ranges[mid * 2 + 1] -> lo = mid + 1
                else -> return true
            }
        }
        return false
    }
