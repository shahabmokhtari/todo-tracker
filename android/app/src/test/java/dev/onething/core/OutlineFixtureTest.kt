/**
 * tests/fixtures/outline.json (generated by the C# core): the Tasks tree draws the same rows, path, zoom and Open to
 * sets as the server, the web app and the Mac/iPhone, for every case.
 */
class OutlineFixtureTest {
    private val fixture: JsonObject by lazy {
        var dir: File? = File("").absoluteFile
        while (dir != null && !File(dir, "tests/fixtures/outline.json").isFile) dir = dir.parentFile
        Json.parseToJsonElement(File(dir ?: error("tests/fixtures not found"), "tests/fixtures/outline.json").readText()).jsonObject
    }

    private fun JsonObject.text(key: String): String? = (this[key] as? JsonPrimitive)?.takeIf { it.isString }?.content
    private fun JsonObject.flag(key: String): Boolean = (this[key] as? JsonPrimitive)?.boolean ?: false
    private fun strings(e: JsonElement?): List<String> = (e as? JsonArray)?.map { it.jsonPrimitive.content }.orEmpty()

    private val now get() = Instant.parse(fixture.text("now"))
    private val tasks get() = fixture["tasks"]!!.jsonArray.map { it.jsonObject }

    /** The board the C# core built: tasks added at `now`, then finished, snoozed and archived, in that order. */
    private fun build(): Pair<TaskBoard, Map<String, UUID>> {
        val board = TaskBoard().apply { zone = ZoneOffset.UTC }
        val names = strings(fixture["groups"])
        for (name in names.drop(board.groups.size)) board.addGroup(name, now = now)
        assertEquals(names, board.groups.map { it.name })
        val ids = linkedMapOf<String, UUID>()
        for (t in tasks) {
            ids[t.text("key")!!] = board.addTask(
                NewTask(
                    t.text("title")!!,
                    parentId = t.text("parent")?.let { ids[it] },
                    groupId = t.text("group")?.let { g -> board.groups.first { it.name == g }.id },
                    sequential = t.flag("sequential"),
                ),
                now = now,
            ).id
        }
        val snoozed = Instant.parse(fixture.text("snoozedUntil"))
        tasks.filter { it.flag("done") }.forEach { board.complete(ids[it.text("key")]!!, now = now) }
        tasks.filter { it.flag("snoozed") }.forEach { board.scheduleNextAction(ids[it.text("key")]!!, snoozed, now = now) }
        tasks.filter { it.flag("archived") }.forEach { board.archive(ids[it.text("key")]!!, now = now) }
        return board to ids
    }

    @Test
    fun aRowShowsOnlyTheTagsItsParentDoesNotAlsoHave() {
        val cases = fixture["tags"]!!.jsonArray.map { it.jsonObject }
        assertTrue(cases.size >= 10)
        for (t in cases) {
            val parent = (t["parent"] as? JsonArray)?.map { it.jsonPrimitive.content }
            assertEquals(t.toString(), t["shown"]!!.jsonArray.map { it.jsonPrimitive.content }, Outline.shownTags(t["tags"]!!.jsonArray.map { it.jsonPrimitive.content }, parent))
        }
    }

    @Test
    fun titlesLeaveOutTheParentsNameTheWayTheFixtureSays() {
        for (t in fixture["titles"]!!.jsonArray.map { it.jsonObject }) {
            assertEquals(t.toString(), t.text("shown"), Outline.shownTitle(t.text("title")!!, t.text("parent"), t.text("parentShown")))
        }
    }

    @Test
    fun everyCaseDrawsTheTreeTheFixtureSays() {
        val (board, ids) = build()
        val keys = ids.entries.associate { it.value to it.key }
        val groupIds = board.groups.associate { it.name to it.id }
        val groupNames = board.groups.associate { it.id to it.name }
        fun key(id: UUID?): JsonElement = id?.let { JsonPrimitive(keys[it] ?: groupNames[it] ?: "?") } ?: JsonNull
        fun rowsOf(options: OutlineOptions): JsonArray = JsonArray(
            Outline.rows(board, options, now).map { r ->
                JsonObject(
                    linkedMapOf(
                        "kind" to JsonPrimitive(r.kind.name.lowercase()),
                        "id" to key(r.id),
                        "depth" to JsonPrimitive(r.depth),
                        "title" to JsonPrimitive(r.title),
                        "fullTitle" to JsonPrimitive(r.fullTitle),
                        "hasChildren" to JsonPrimitive(r.hasChildren),
                        "expanded" to JsonPrimitive(r.expanded),
                        "done" to JsonPrimitive(r.done),
                        "total" to JsonPrimitive(r.total),
                        "left" to JsonPrimitive(r.left),
                        "state" to (r.state?.let { JsonPrimitive(it.wire) } ?: JsonNull),
                        "outdent" to JsonPrimitive(r.canOutdent),
                    ),
                )
            },
        )

        val cases = fixture["cases"]!!.jsonArray.map { it.jsonObject }
        assertTrue("every case of the fixture", cases.size >= 27)
        for (c in cases) {
            val name = c.text("name")
            val o = c["options"]!!.jsonObject
            val options = OutlineOptions(
                groupId = o.text("group")?.let { groupIds[it]!! },
                zoomId = o.text("zoom")?.let { ids[it] ?: UUID.randomUUID() },
                show = Outline.parseShow(o.text("show"))!!,
                query = o.text("query").orEmpty(),
                expanded = strings(o["expanded"]).map { ids[it]!! }.toSet(),
                closedGroups = strings(o["closedGroups"]).map { groupIds[it]!! }.toSet(),
            )
            assertEquals("$name: zoom", c["zoom"], key(Outline.resolveZoom(board, options, now)))
            assertEquals("$name: remembered zoom", c["remembered"], key(Outline.rememberedZoom(board, options)))
            assertEquals("$name: zoom up", c["zoomUp"], key(Outline.zoomUp(board, options, now)))
            assertEquals("$name: rows", c["rows"], rowsOf(options))
            val path = JsonArray(
                Outline.path(board, options, now).map { p ->
                    JsonObject(
                        linkedMapOf(
                            "kind" to JsonPrimitive(p.kind.name.lowercase()),
                            "id" to key(p.id),
                            "title" to JsonPrimitive(p.title),
                            "done" to JsonPrimitive(p.done),
                            "total" to JsonPrimitive(p.total),
                        ),
                    )
                },
            )
            assertEquals("$name: path", c["path"], path)
            val place = Outline.newTaskPlace(board, options, now)
            val newTask = c["newTask"]!!.jsonObject
            assertEquals("$name: new task's parent", newTask["parent"], key(place.parentId))
            assertEquals("$name: new task's group", newTask["group"], key(place.groupId))
            (c["openTo"] as? JsonObject)?.forEach { (level, want) ->
                val open = Outline.openTo(board, options, OutlineLevel.valueOf(level.uppercase()), now)
                val w = want.jsonObject
                assertEquals("$name: open to $level: expanded", strings(w["expanded"]), ids.entries.filter { it.value in open.expanded }.map { it.key })
                assertEquals("$name: open to $level: closed groups", strings(w["closedGroups"]), board.groups.filter { it.id in open.closedGroups }.map { it.name })
                assertEquals("$name: open to $level: rows", w["rows"], rowsOf(options.copy(expanded = open.expanded, closedGroups = open.closedGroups)))
            }
        }
    }

    /** Each group's name, then its top-level tasks (archived ones too) and their subtasks, two spaces per level. */
    private fun tree(board: TaskBoard, keys: Map<UUID, String>): JsonArray {
        val lines = mutableListOf<String>()
        fun walk(items: List<WorkItem>, depth: Int) {
            for (item in items) {
                lines.add("  ".repeat(depth) + (keys[item.id] ?: "?"))
                walk(item.children, depth + 1)
            }
        }
        for (group in board.groups) {
            lines.add(group.name)
            walk(board.items.filter { it.groupId == group.id }, 1)
        }
        return JsonArray(lines.map { JsonPrimitive(it) })
    }

    /** A move the way the Tasks screen plans it (BoardViewModel, TasksScreen), null when it doesn't make it. */
    private fun plan(board: TaskBoard, ids: Map<String, UUID>, options: OutlineOptions, move: JsonObject): PlannedMove? {
        val scope = BoardScope(board, options.groupId, options.query)
        val keeps = Outline.keeps(board, options, now)
        val task = move.text("task")?.let { ids[it]!! }
        val groupOf = { name: String -> board.groups.first { it.name == name }.id }
        return when (move.text("do")) {
            "indent" -> scope.indent(task!!, keeps)
            "outdent" -> {
                // Only from a row that can move out here (not at the top of a zoom), as the ⋯ menu checks.
                val open = Outline.openTo(board, options, OutlineLevel.ALL, now)
                val row = Outline.rows(board, options.copy(expanded = open.expanded), now).firstOrNull { it.id == task }
                if (row?.canOutdent == true) scope.outdent(task!!) else null
            }
            "up" -> scope.step(task!!, -1, keeps)
            "down" -> scope.step(task!!, 1, keeps)
            "drop" -> scope.drop(task!!, ids[move.text("target")]!!, OutlineMoves.Zone.valueOf(move.text("zone")!!.uppercase()))
            "dropOnGroup" -> scope.dropOnGroup(task!!, groupOf(move.text("group")!!))
            "newTask" -> {
                // As TasksScreen's New task: added where it goes, first.
                val place = Outline.newTaskPlace(board, options, now)
                board.addInPlace("New", place.parentId, null, if (place.parentId == null) Stage.NEXT else null, place.groupId, UUID.randomUUID(), now = now, first = place.parentId == null)
                PlannedMove(emptyList(), null)
            }
            else -> error("${move.text("do")}")
        }
    }

    @Test
    fun everyMoveEndsAtTheSameTreeAsTheOtherApps() {
        val (start, startIds) = build()
        assertEquals("the board the moves start from", fixture["tree"], tree(start, startIds.entries.associate { it.value to it.key }))
        val moves = fixture["moves"]!!.jsonArray.map { it.jsonObject }
        assertTrue("every move of the fixture", moves.size >= 25)
        for (m in moves) {
            val name = m.text("name")
            val (board, ids) = build()
            val o = m["options"]!!.jsonObject
            val options = OutlineOptions(
                groupId = o.text("group")?.let { g -> board.groups.first { it.name == g }.id },
                zoomId = o.text("zoom")?.let { ids[it]!! },
                show = Outline.parseShow(o.text("show"))!!,
                query = o.text("query").orEmpty(),
            )
            val planned = plan(board, ids, options, m["move"]!!.jsonObject)
            if (m.text("tree") == "refused") {
                assertEquals("$name: refused", null, planned)
                continue
            }
            board.applyPlanned(planned ?: error("$name: not planned"), now = now)
            val keys = ids.entries.associate { it.value to it.key }.toMutableMap()
            board.allItems.firstOrNull { it.title == "New" }?.let { keys[it.id] = "new" }
            assertEquals("$name: tree", m["tree"], tree(board, keys))
        }
    }

    @Test
    fun theSearchKeepsWhatTheServerKeeps() {
        val (board, ids) = build()
        for (c in fixture["cases"]!!.jsonArray.map { it.jsonObject }.filter { it["keep"] != null }) {
            val query = c["options"]!!.jsonObject.text("query")!!
            val kept = Outline.searchKeeps(board, query)
            assertEquals(c.text("name"), strings(c["keep"]), ids.entries.filter { it.value in kept }.map { it.key })
        }
    }
}
