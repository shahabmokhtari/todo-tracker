package dev.onething.core

import java.io.File
import java.time.Instant
import java.time.ZoneOffset
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Test

/**
 * tests/fixtures/board-moves.json (generated by the C# core): cards move between the Board's columns, and tasks in the
 * outline, exactly as the server moves them.
 */
class BoardMovesFixtureTest {
    private fun fixture(): JsonObject {
        var dir: File? = File("").absoluteFile
        while (dir != null && !File(dir, "tests/fixtures/board-moves.json").isFile) dir = dir.parentFile
        return Json.parseToJsonElement(File(dir ?: error("tests/fixtures not found"), "tests/fixtures/board-moves.json").readText()).jsonObject
    }

    private fun JsonObject.text(key: String): String? = (this[key] as? JsonPrimitive)?.takeIf { it.isString }?.content

    @Test
    fun cardsAndTasksMoveLikeTheServerMovesThem() {
        val cases = fixture()["cases"]!!.jsonArray.map { it.jsonObject }
        assertTrue(cases.size >= 8)
        val t0 = Instant.parse("2026-01-05T09:00:00Z")
        for (case in cases) {
            val name = case.text("name")
            val board = TaskBoard().apply { zone = ZoneOffset.UTC }
            val tasks = linkedMapOf<String, WorkItem>()
            case["steps"]!!.jsonArray.map { it.jsonObject }.forEachIndexed { n, step ->
                val at = t0.plusSeconds(n * 60L)
                val what = "$name, step ${n + 1} (${step.text("do")})"
                if (step.text("do") == "check") {
                    check(board, tasks, step, at, what)
                    return@forEachIndexed
                }
                val fails = (step["fails"] as? JsonPrimitive)?.boolean ?: false
                try {
                    run(step, board, tasks, at)
                    if (fails) fail("$what should have been refused")
                } catch (e: BoardException) {
                    if (!fails) fail("$what failed: ${e.message}")
                }
            }
        }
    }

    private fun run(step: JsonObject, board: TaskBoard, tasks: MutableMap<String, WorkItem>, at: Instant) {
        fun task(field: String = "task") = tasks[step.text(field)]!!.id
        val group = step.text("group")?.let { name -> board.groups.first { it.name == name }.id }
        when (step.text("do")) {
            "add" -> {
                val item = board.addTask(
                    NewTask(step.text("title")!!, parentId = step.text("parent")?.let { tasks[it]!!.id }, groupId = group, stage = step.text("stage")?.let { Stage.of(it) }),
                    now = at,
                )
                step.text("repeat")?.let { board.update(item.id, TaskChanges(repeat = it), now = at) }
                tasks[step.text("key")!!] = item
            }
            "stage" -> board.applyMove(BoardMove.SetStage(task(), Stage.of(step.text("stage"))), now = at)
            "complete" -> board.applyMove(BoardMove.Complete(task()), now = at)
            "reopen" -> board.reopen(task(), now = at)
            "archive" -> board.archive(task(), now = at)
            "timer" -> board.startTimer(task(), now = at)
            "reorder" -> board.applyMove(BoardMove.Reorder(task(), step.text("before")?.let { tasks[it]!!.id }), now = at)
            "reorderAfter" -> board.applyMove(BoardMove.ReorderAfter(task(), task("after")), now = at)
            "move" -> board.applyMove(
                BoardMove.Move(task(), step.text("parent")?.let { tasks[it]!!.id }, group, (step["index"] as? JsonPrimitive)?.int),
                now = at,
            )
            "indent", "outdent" -> {
                val id = task()
                val moves = (if (step.text("do") == "indent") OutlineMoves.indent(board, id) else OutlineMoves.outdent(board, id))
                    ?: throw BoardException("Can't move it there.")
                for (m in moves) board.applyMove(m, now = at)
            }
            else -> fail("unknown step $step")
        }
    }

    private fun check(board: TaskBoard, tasks: Map<String, WorkItem>, step: JsonObject, at: Instant, what: String) {
        val keys = tasks.entries.associate { it.value.id to it.key }
        fun key(item: WorkItem) = keys[item.id] ?: "?"
        fun strings(e: Any?) = (e as JsonArray).map { it.jsonPrimitive.content }
        val tree = mutableListOf<String>()
        fun walk(item: WorkItem, depth: Int) {
            tree.add("  ".repeat(depth) + key(item))
            item.children.forEach { walk(it, depth + 1) }
        }
        board.items.forEach { walk(it, 0) }
        assertEquals("$what: tree", strings(step["tree"]), tree)
        val groups = board.items.associate { root -> key(root) to board.groups.first { it.id == root.groupId }.name }
        assertEquals("$what: groups", step["groups"]!!.jsonObject.mapValues { it.value.jsonPrimitive.content }, groups)
        val columns = BoardColumns.of(board.items, at)
        val expected = step["columns"]!!.jsonObject
        for (column in BoardColumn.entries) {
            assertEquals("$what: ${column.displayName}", strings(expected[column.wire]), columns[column]!!.map(::key))
        }
        assertEquals("$what: done", strings(step["done"]), board.allItems.filter { it.isDone }.map(::key))
        assertEquals("$what: archived", strings(step["archived"]), board.items.filter { it.archivedAt != null }.map(::key))
    }
}
